# -*- coding: utf-8 -*-
"""기아 분기별 판매보증충당부채 (DART 연결 주석, 판매보증충당부채 열만, 단위 백만원)
누적 설정액(연초~분기말) -> 분기 설정액 = 누적 차분. 매출액은 3개월 매출(4분기 = 연간 - 3분기 누적).
2014~2020 사업보고서는 2021.12.10 기재정정본(정정사유: 관계기업 이연법인세 오류수정, 충당부채와 무관).
2012~2014 분기/반기/2012~13 사업보고서는 첨부 연결검토/감사보고서 주석에서 추출."""
import os, pandas as pd, numpy as np
HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'dart')
# 연도: (Q1,H1,Q3,FY 누적설정액), (Q1,Q2,Q3 3개월 매출, FY 매출), (분기말 잔액 Q1,H1,Q3,FY)
D = {
2012: ((231856, 559488, 815754, 1040461), (11790039, 12550870, 11624991, 47242933), (None, 1776481, 1822560, 1802983)),
2013: ((275129, 583199, 841957, 1050494), (11084819, 13112608, 11633869, 47597897), (None, 2039967, 2043144, 2011256)),
2014: ((289295, 526497, 774610, 997232), (11925823, 12054489, 11414811, 47097049), (2094485, 2035768, 2046567, 2037303)),
2015: ((282281, 619399, 996118, 1365271), (11177668, 12441109, 13110901, 49521447), (2066875, 2216975, 2373528, 2366662)),
2016: ((416295, 909342, 1195599, 1811971), (12649367, 14449981, 12698855, 52712906), (2532363, 2759272, 2706381, 3055758)),
2017: ((567711, 921690, 1429722, 2049682), (12843896, 13578443, 14107692, 53535680), (3319634, 3479629, 3607506, 3574847)),
2018: ((126449, 606503, 1254496, 1601455), (12562201, 14060127, 14074306, 54169813), (3468418, 3403694, 3558387, 3684438)),
2019: ((196842, 646179, 1222314, 1692633), (12444350, 14506654, 15089541, 58145959), (3585441, 3539530, 3876147, 3619302)),
2020: ((358126, 660404, 1591720, 2908121), (14566900, 11368841, 16321783, 59168096), (3682381, 3539585, 4423187, 4556643)),
2021: ((453202, 884699, 1265567, 1823375), (16581735, 18339491, 17752762, 69862366), (4650086, 4613326, 4625021, 4640702)),
2022: ((438987, 1023801, 3611938, 4266213), (18357236, 21875984, 23161648, 86559029), (4640515, 4824349, 7225529, 6642777)),
}
rows = []
for y, (cum, rev, end) in D.items():
    qset = [cum[0], cum[1] - cum[0], cum[2] - cum[1], cum[3] - cum[2]]
    qrev = [rev[0], rev[1], rev[2], rev[3] - sum(rev[:3])]
    for q in range(4):
        rows.append({'연도': y, '분기': q + 1, '1년동안 충당부채 누적': cum[q], '분기별 설정액(백만단위)': qset[q],
                     '매출액(백만원)': qrev[q], '분기별 설정률': qset[q] / qrev[q], '분기말 잔액': end[q]})
k = pd.DataFrame(rows)
k['Quarter'] = k.연도.astype(str) + 'Q' + k.분기.astype(str)
# 설정률 이상치: 직전 8분기 중앙값 대비 배수
k['설정률_배수(직전8Q중앙값)'] = k['분기별 설정률'] / k['분기별 설정률'].shift(1).rolling(8, min_periods=4).median()

h = pd.read_excel(os.path.join(HERE, '현대_분기별충당부채_DART대조.xlsx'))
h['Quarter'] = h.연도.astype(str) + 'Q' + h.분기.astype(str)
h['현대_배수'] = h.분기설정률 / h.분기설정률.shift(1).rolling(8, min_periods=4).median()
cmp_ = k[['Quarter', '분기별 설정액(백만단위)', '분기별 설정률', '설정률_배수(직전8Q중앙값)']].rename(
    columns={'분기별 설정액(백만단위)': '기아_설정액', '분기별 설정률': '기아_설정률', '설정률_배수(직전8Q중앙값)': '기아_배수'}).merge(
    h[['Quarter', '분기별 설정액(백만단위)', '분기설정률', '현대_배수']].rename(
        columns={'분기별 설정액(백만단위)': '현대_설정액', '분기설정률': '현대_설정률'}), on='Quarter', how='left')
src = pd.DataFrame({'항목': ['출처', '정의', '정정공시', '검증'], '내용': [
    'DART 기아(00106641) 분기·반기·사업보고서 연결재무제표 주석 충당부채 변동표(판매보증충당부채 열)',
    '분기 설정액 = 당기 누적 설정액 차분, 매출 = 3개월 매출(4Q=연간-3Q누적), 설정률 = 설정액/매출',
    '2014~2020 사업보고서 2021.12.10 기재정정(관계기업 이연법인세 오류수정) - 판매보증충당부채 수치 영향 없음',
    '연간 기말잔액 = 차기 1Q 기초잔액 연결 확인']})
out = os.path.join(HERE, '기아_분기별충당부채_DART.xlsx')
with pd.ExcelWriter(out) as w:
    k.drop(columns='Quarter').to_excel(w, '기아_분기', index=False)
    cmp_.round(4).to_excel(w, '현대_기아_비교', index=False)
    src.to_excel(w, '출처', index=False)
pd.set_option('display.width', 250)
print(cmp_[(cmp_.Quarter >= '2015Q1')].round(3).to_string(index=False))
