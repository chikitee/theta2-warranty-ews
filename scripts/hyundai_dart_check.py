# -*- coding: utf-8 -*-
"""현대차 분기별 판매보증충당부채 DART 대조 (연결 주석 '판매보증' 열, 연초~분기말 누적 설정(전입)액, 백만원)
기존 파일(클로드2/분기별충당부채_감사보고서기준.xlsx)과 비교 -> 수정본 별도 저장 (원본 미변경)"""
import os, pandas as pd
HERE = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'data', 'dart')
CUM = {2012: (198763, 494118, 598198, 712587), 2013: (360413, 692411, 786377, 773917),
       2014: (277419, 368537, 664316, 866416), 2015: (205200, 464921, 798679, 998395),
       2016: (255495, 723840, 871005, 1194945), 2017: (363896, 935713, 1183423, 1392351),
       2018: (378586, 822652, 1614025, 1703173), 2019: (490262, 1084145, 2263223, 2477648),
       2020: (722771, 1239895, 4002825, 5170165), 2021: (696844, 1569722, 2225183, 2900638),
       2022: (815086, 1951704, 4402989, 4347523)}
old = pd.read_excel(os.path.join(HERE, '분기별충당부채_감사보고서기준.xlsx'))
rows = []
for y, c in CUM.items():
    qs = [c[0], c[1] - c[0], c[2] - c[1], c[3] - c[2]]
    for q in range(4):
        rows.append({'연도': y, '분기': q + 1, '1년동안 충당부채 누적': c[q], '분기별 설정액(백만단위)': qs[q]})
new = pd.DataFrame(rows).merge(old[['연도', '분기', '매출액', '1년동안 충당부채 누적', '분기별 설정액(백만단위)']]
                               .rename(columns={'1년동안 충당부채 누적': '기존_누적', '분기별 설정액(백만단위)': '기존_분기설정액'}),
                               on=['연도', '분기'], how='left')
new['분기설정률'] = new['분기별 설정액(백만단위)'] / (new.매출액 / 1e6)
new['차이(DART-기존)'] = new['분기별 설정액(백만단위)'] - new.기존_분기설정액
new = new[['연도', '분기', '1년동안 충당부채 누적', '분기별 설정액(백만단위)', '매출액', '분기설정률', '기존_누적', '기존_분기설정액', '차이(DART-기존)']]
note = pd.DataFrame({'항목': ['출처', '결과', '2022Q4', '모델 영향'], '내용': [
    'DART 현대자동차(00164742) 분기·반기·사업보고서 연결재무제표 주석 충당부채 변동표 판매보증 열(2014~2020 사업보고서는 2022.02.17 기재정정본, 2022 사업보고서 정정은 임원보수 건)',
    '기존 파일은 연결 현금흐름표 조정항목 "판매보증충당부채전입액" 기준(오류 아님, 2018Q1 366,595·2022Q3 4,047,908 원문 확인). 본 파일은 주석 변동표 "설정액" 기준 -> 2018년 이후 정의 차이 발생. 기아 비교용(주석 기준 통일)',
    '두 기준 모두 음수: 주석 설정액 -55,466 / 현금흐름표 전입액 -40,450. 4분기 순환입',
    '기존 DPA·v4 모델 결과 영향 없음. 현대 단독 분석은 기존(현금흐름표) 기준 유지, 기아와 비교 시에만 본 파일 사용']})
out = os.path.join(HERE, '현대_분기별충당부채_DART대조.xlsx')
with pd.ExcelWriter(out) as w:
    new.to_excel(w, sheet_name='현대_분기_DART', index=False); note.to_excel(w, sheet_name='대조결과', index=False)
print(new[new['차이(DART-기존)'] != 0][['연도', '분기', '분기별 설정액(백만단위)', '기존_분기설정액', '차이(DART-기존)']].to_string(index=False))
